def test_a_gated_write_switches_a_real_relay_and_reads_back(cli_writable):
    """``--yes`` plus a nominated relay: the contact moves, and a second process sees it.

    The read-back is a *separate invocation*, which is the part an in-process
    test cannot do: it proves the switch outlived the process that made it. A
    one-shot CLI whose effects vanished at exit would pass every single-process
    assertion.

    Also the one place the ``disarm_watchdog=False`` lifecycle override is
    load-bearing on hardware: without it the read-back invocation's own open
    would send ``WD0``, and a read would be silently changing device state.
    """
    relay = cli_writable

    on = _run("--yes", "adu218", "set-relay-state", str(relay), "on")
    assert on.returncode == 0, on.stderr
    assert "verified: on" in on.stdout

    seen = _run("--json", "adu218", "relay-states")
    assert seen.returncode == 0, seen.stderr
    assert json.loads(seen.stdout)["relays"][str(relay)] is True

    off = _run("--yes", "adu218", "reset-relays")
    assert off.returncode == 0, off.stderr

    cleared = _run("--json", "adu218", "relay-states")
    assert cleared.returncode == 0, cleared.stderr
    assert json.loads(cleared.stdout)["relays"][str(relay)] is False


def test_reset_relays_needs_no_confirmation_on_hardware(cli_writable):
    """De-energising is tier 2, and that is checked against the device.

    The in-process test asserts the *tier table* says so. This asserts the
    device agrees: ``reset-relays`` with no ``--yes`` reaches the hardware and
    returns 0. Reaching the safe state must never need more ceremony than
    leaving it, or an operator fighting a live output has a gate in the way —
    and that property is worth proving where it would actually be used.
    """
    proc = _run("adu218", "reset-relays")

    assert proc.returncode == 0, proc.stderr
    assert "Nothing has been sent to the device." not in proc.stderr
