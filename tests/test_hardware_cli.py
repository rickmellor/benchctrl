def test_a_generated_read_reaches_the_real_device(adu_present):
    """The whole point of the feature, as one process.

    ``relay-states`` is the question that motivated the CLI, and it is generated
    — nothing about this subcommand was hand-written, so a pass shows reflection
    over ``_TOOLS`` produced something that works against silicon rather than
    something that merely parses.

    Asserts on the *identity* fields rather than the relay states, because the
    states are whatever the bench is doing; the model and the relay count are
    facts about the device, so a wrong device or a stubbed answer fails.
    """
    proc = _run("adu218", "info")

    assert proc.returncode == 0, proc.stderr
    assert "model: ADU218" in proc.stdout
    assert "relay_count: 8" in proc.stdout


def test_json_output_is_parseable_and_carries_the_device_shape(adu_present):
    """``--json`` is the machine contract, so it must parse and be complete.

    The default rendering is lossy on purpose (``on``/``off`` for booleans), so
    a script that needs the value reads ``--json``. Asserting it parses *and*
    carries all eight relays as bools is what makes it usable: a renderer that
    leaked its formatting into the JSON would still parse.
    """
    proc = _run("--json", "adu218", "relay-states")

    assert proc.returncode == 0, proc.stderr
    payload = json.loads(proc.stdout)

    assert sorted(int(k) for k in payload["relays"]) == list(range(8))
    assert all(isinstance(v, bool) for v in payload["relays"].values())

    # The mask has to agree with the per-relay dict, or a script reading one and
    # a human reading the other would draw different conclusions from the same
    # invocation. Recomputed rather than compared to a constant, since whatever
    # the bench is doing is legitimate.
    assert payload["mask"] == sum(
        1 << int(k) for k, on in payload["relays"].items() if on
    )
    assert sorted(payload["energised"]) == sorted(
        int(k) for k, on in payload["relays"].items() if on
    )


def test_booleans_render_as_on_off_against_a_real_device(adu_present):
    """The render fix, on the device whose whole answer is on/off.

    ``adu218_relay_states`` returns a *nested* dict, which is where a
    JSON-dumping renderer produced ``relays: {"0": false, …}`` — the bool
    rendering never reaching the values that needed it most. Checked here rather
    than only in-process because the fixture that exposed it is the real tool's
    real return shape, and a hand-built fixture is what let it through.
    """
    proc = _run("adu218", "relay-states")

    assert proc.returncode == 0, proc.stderr
    assert "0=off" in proc.stdout or "0=on" in proc.stdout
    assert "false" not in proc.stdout.lower()
    assert "True" not in proc.stdout


def test_a_nested_collection_is_bracketed_not_dumped(adu_present):
    """``input-states`` returns dict-of-lists — the other shape the fix covers.

    The separators would otherwise merge: ``ports: A=off, off, off, B=…`` cannot
    be read. This is the case that justifies bracketing one level down while
    leaving the top level bare.
    """
    proc = _run("adu218", "input-states")

    assert proc.returncode == 0, proc.stderr
    assert "ports: A=[" in proc.stdout
    assert "B=[" in proc.stdout
    assert "{" not in proc.stdout


