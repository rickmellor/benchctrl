"""The generated CLI as an operator actually runs it: a real process, real hardware.

Everything in ``tests/test_cli_generated.py``, ``test_cli_main.py`` and
``test_cli_tiers.py`` calls ``main(argv)`` in-process with fakes underneath. That
is the right place for the tier table, the argument coercion and the lifecycle
overrides, and it proves all of them. What it cannot prove is the two claims that
are properties of *a process against a device*:

1. **A subcommand generated by reflection actually drives the instrument**, end
   to end, through the real open/call/teardown lifecycle in a process that exits
   inside a second. An in-process test shares the interpreter with pytest, so it
   never exercises the thing the CLI exists to do: start cold, open, read, tear
   down, exit. If the implicit open were wrong, or teardown deadlocked, only a
   real invocation would show it.

2. **The exit codes are what a shell script sees.** ``main()`` returning 3 and
   ``$? == 3`` are different claims — the second also depends on ``__main__``,
   on nothing swallowing the return value, and on no traceback escaping. Scripts
   branch on ``$?``, so ``$?`` is what gets asserted here.

Why the gate tests live here rather than only in-process
--------------------------------------------------------

The refusal path is the one case where hardware is *irrelevant by construction*:
the gate is checked before the device is opened (``cli_generated._check_tier``),
so a refusal is a refusal with nothing attached. That makes an in-process test
sufficient for the message, and it exists. What is asserted here instead is the
part that needs the device: that a satisfied gate does **not** stop at the gate
but goes on to reach the instrument. A test that only shows "no ``--yes`` → 3"
cannot tell a working gate from one that refuses everything; the pair can.

So the discriminator is the exit code of the *satisfied* case, and it is checked
against a real device rather than against an absent one. With no ADU218 present
the satisfied run also fails — with 2, the connection code — and 2-vs-3 would
then be indistinguishable from a gate that never opened anything.

What this file deliberately does not do
---------------------------------------

**It does not switch a relay it was not told it may switch.** ``adu218
set-relay-state`` needs ``--yes``, and the CLI has no ``allowed_relays`` flag on
purpose (an allowlist a caller can widen per invocation is not an allowlist), so
a CLI write reaches whatever relay is named with the driver's permissive default.
The write test therefore takes the same ``BENCHCTRL_ADU218_RELAY`` nomination as
``test_hardware_ontrak_adu218.py`` and skips without an explicit opt-in, and it
restores the relay afterwards through the CLI's own de-energising path — which
is also how ``reset-relays`` gets exercised as the tier-2 case it is classified
as.

**It does not arm the watchdog.** ``set-watchdog`` is the one env-gated ADU218
tool, and its consequence outlives the process: the relays drop by timeout after
the CLI has exited, with nothing left to feed it. The trip itself is witnessed on
hardware in ``test_hardware_ontrak_adu218.py`` with the DMM across the contact
and an explicit opt-in. Here only the *refusal* is checked, which needs no arming.

Running it
----------

The ADU218 is found by USB descriptor; there is no address to supply. Every test
skips if it is not attached, because "not plugged in" is a fact about the bench
and a red test for it trains people to ignore this file.

    BENCHCTRL_ADU218_RELAY       the relay a CLI write may switch (default 7)
    BENCHCTRL_CLI_HW_WRITE=1     allow the one CLI relay write (default: skip)

These run on the **bench machine**, against local devices — the board carries
the hardware, so ``python3 -m benchctrl adu218 …`` there needs no endpoint
token. Nothing here uses ``--remote``: that path is covered by
``tests/test_remote_ontrak_adu218.py``, and pointing it at a board whose agent
holds the writer claim would test claim contention rather than the CLI.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys

import pytest

pytestmark = pytest.mark.hardware

#: The relay a CLI write may switch. Same variable and same default as
#: ``test_hardware_ontrak_adu218.TEST_RELAY``, deliberately: two files
#: disagreeing about which relay is safe to move is exactly the drift that ends
#: with a leads-connected contact switching under a DMM that is mid-reading.
TEST_RELAY = int(os.environ.get("BENCHCTRL_ADU218_RELAY", "7"))

#: Timeout for one invocation. A CLI one-shot opens, calls and exits well inside
#: a second on this hardware; this is generous so a slow USB enumeration is not
#: reported as a hang, while still failing rather than blocking the suite.
RUN_TIMEOUT_S = 60.0


def _run(*args: str, env_extra: dict | None = None) -> subprocess.CompletedProcess:
    """One real ``benchctrl`` process, captured.

    Invoked as ``-m benchctrl`` rather than the console script because the board
    has no pip and reaches the package through ``PYTHONPATH`` — the console
    script is not installed there, and a test that needs it would skip on the
    one machine that has the instruments.

    ``sys.executable`` rather than ``python3`` so the subprocess is the same
    interpreter running the tests, and a passing test cannot be a different
    Python finding a different copy of the package.
    """
    env = dict(os.environ)
    if env_extra:
        env.update(env_extra)
    return subprocess.run(
        [sys.executable, "-m", "benchctrl", *args],
        capture_output=True,
        text=True,
        timeout=RUN_TIMEOUT_S,
        env=env,
    )


def _skip_unless_adu_present() -> None:
    """Skip the module's device tests unless a real ADU218 answers.

    Probes with a *read* subcommand, which is the CLI path under test — so a
    skip here means the CLI cannot reach the device, which is the same condition
    the tests care about. Keying the skip on the driver directly would let a
    broken CLI skip instead of fail.
    """
    proc = _run("adu218", "info")
    if proc.returncode != 0:
        pytest.skip(
            f"ADU218 not reachable through the CLI (rc={proc.returncode}): "
            f"{proc.stderr.strip()[:200]}"
        )


@pytest.fixture(scope="module")
def adu_present() -> None:
    _skip_unless_adu_present()


@pytest.fixture()
def cli_writable(adu_present) -> int:
    """The relay a CLI write may switch, or a skip, with the relay restored.

    De-energises through ``reset-relays`` on the way out rather than
    ``set-relay-state <n> off``: it is the driver's allowlist-bypassing safe
    path, so the restore cannot itself be refused, and it recovers the bench
    even if the test died between the two writes.
    """
    if os.environ.get("BENCHCTRL_CLI_HW_WRITE") != "1":
        pytest.skip(
            "set BENCHCTRL_CLI_HW_WRITE=1 to let the CLI switch relay "
            f"{TEST_RELAY}. The CLI has no allowed_relays flag, so a write "
            "reaches whatever relay is named"
        )
    try:
        yield TEST_RELAY
    finally:
        _run("--yes", "adu218", "reset-relays")


