def test_a_refused_write_exits_3_and_sends_nothing():
    """No ``--yes`` on a tier-1 tool: 3, and the operator is told nothing moved.

    Runs with no device fixture on purpose — the gate is checked before the open,
    so this must hold whether or not an ADU218 is attached, and a version that
    needed the device would be asserting the wrong thing.

    3 rather than 2 is the load-bearing half: a script has to be able to tell
    "you did not authorise this" from "the device is not there", and both are
    non-zero.
    """
    proc = _run("adu218", "set-relay-state", str(TEST_RELAY), "on")

    assert proc.returncode == 3, (proc.returncode, proc.stderr)
    assert "needs --yes" in proc.stderr
    assert "Nothing has been sent to the device." in proc.stderr
    assert proc.stdout == ""


def test_an_env_gated_write_exits_3_with_yes_alone():
    """``--yes`` is not enough for ``set-watchdog``, and the message says why.

    Two factors because they are different claims: ``--yes`` says the command was
    intended, the variable says the operator knows what is physically attached.
    Asserting the variable is *named* matters — an operator who cannot discover
    which variable to set will reach for the source, and the gate stops being a
    gate the first time someone exports everything.
    """
    proc = _run("--yes", "adu218", "set-watchdog", "3")

    assert proc.returncode == 3, (proc.returncode, proc.stderr)
    assert "BENCHCTRL_ADU218_ARM_WATCHDOG" in proc.stderr
    assert "Nothing has been sent to the device." in proc.stderr
    assert proc.stdout == ""


def test_satisfying_the_env_gate_gets_past_it_to_the_device(adu_present):
    """The discriminator: a satisfied gate reaches the instrument.

    Without this, ``test_an_env_gated_write_exits_3_with_yes_alone`` is equally
    consistent with a gate that refuses *everything* — a permanently-closed gate
    passes every refusal assertion in this file.

    ``set-watchdog 0`` is the disarming direction, so the gate is satisfied and
    exercised while nothing is left armed after the process exits. That it
    returns 0 against a real device is the proof the gate was the only obstacle;
    with no ADU218 attached this would be 2, which is why it takes the fixture.
    """
    proc = _run(
        "--yes",
        "adu218",
        "set-watchdog",
        "0",
        env_extra={"BENCHCTRL_ADU218_ARM_WATCHDOG": "1"},
    )

    assert proc.returncode == 0, (proc.returncode, proc.stderr)
    assert "Nothing has been sent to the device." not in proc.stderr
    assert "setting: 0" in proc.stdout


def test_an_absent_device_exits_2_not_3():
    """A device the bench does not have is 2, distinct from a refusal.

    Uses a device key with no hardware on this bench, through a *read* so no
    gate is involved at all. The pairing with the refusals above is what gives
    the exit-code table meaning: 2 and 3 have to be reachable independently, or
    a script cannot branch on them.

    Deliberately takes no device fixture — both halves of that pairing are
    hardware-free, so the distinction is provable on a laptop as well as on the
    bench. Skips if the DP2031 turns out to be attached, since then 0 is the
    correct answer and the test has nothing to say.
    """
    proc = _run("dp2031", "info")
    if proc.returncode == 0:
        pytest.skip("a DP2031 is attached, so this has no absent device to use")

    assert proc.returncode == 2, (proc.returncode, proc.stderr)
    assert "benchctrl error:" in proc.stderr


